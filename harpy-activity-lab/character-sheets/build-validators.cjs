// Compile the supplied schemas for the Activity's browser CSP.
const path = require("node:path");
const Ajv = require("ajv/dist/2020").default;
const standalone = require("ajv/dist/standalone").default;
const { buildSync } = require("esbuild");
const draft = require("./character-draft-v1.schema.json");
const sheet = require("./character-sheet-v1.schema.json");

const ajv = new Ajv({ allErrors: true, code: { source: true } });
ajv.addSchema([draft, sheet]);
buildSync({
  stdin: {
    contents: standalone(ajv, { validateDraft: draft.$id, validateSheet: sheet.$id }),
    resolveDir: __dirname,
  },
  outfile: path.join(__dirname, "validators.mjs"),
  bundle: true,
  platform: "browser",
  banner: { js: "// Generated by build-validators.cjs from the packaged v1 schemas." },
  footer: { js: "export const {validateDraft, validateSheet} = contracts;" },
  // An IIFE namespace keeps the bundled CommonJS exports accessible as browser ESM exports.
  format: "iife",
  globalName: "contracts",
});
